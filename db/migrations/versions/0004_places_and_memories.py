"""places, timeline_memories, unknown_records

Revision ID: 0004_places_and_memories
Revises: 0003_coverage_view
Create Date: 2026-05-03

Three new tables and a maintenance step to keep `places` in sync.

places
------
Promotes Google's `placeId` strings to a first-class entity. Each row
carries a derived centroid + visit_count + first/last_seen, plus a
nullable user_label that survives re-imports. Because the derived
columns must be recomputed after each ingest, we expose a
`refresh_places()` SQL function that the importer calls at the end
of a run; it does an INSERT...ON CONFLICT that DELIBERATELY does NOT
overwrite user_label.

timeline_memories + timeline_memory_places
------------------------------------------
Google's "trip" abstraction — multi-day groupings of places visited.
We store the trip envelope in timeline_memories and the ordered list
of place references in the join table. Activity geometry is NOT
duplicated here; it already lives in segments.

unknown_records
---------------
A catch-all JSONB sink for anything the importer couldn't classify.
Cheap insurance: when Google ships a fourth record kind in some
future export, we capture it instead of silently dropping it.
"""
